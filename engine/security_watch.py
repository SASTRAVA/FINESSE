"""
Security watch — the Security Audit Agent, running constantly.

Opt-in background heartbeat (like crawler.py). On the FIRST cycle it harvests a
baseline of security skills (OWASP cheat sheets, PayloadsAllTheThings) into the
brain so the agent is trained from day one. Every SECURITY_AUDIT_INTERVAL_MIN it:

  1. reads the REAL platform state via the `platform_audit` tool (deterministic evidence),
  2. runs the security_audit agent (agentic loop grounds itself in that evidence + injected
     security requirements),
  3. writes a timestamped report into vault/22_Security/ + a rolling `Security Posture.md`,
  4. emits an alert event on low score / audit anomalies.

Enable in .env:
  SECURITY_AUDIT_ENABLED=1
  SECURITY_AUDIT_INTERVAL_MIN=180

`run_audit()` is also called directly by POST /api/security/audit (run now).
"""
from __future__ import annotations
import asyncio
import json
import re
import time
from pathlib import Path

from .config import cfg
from .mcp import mcp
from .orchestra.events import bus

_SEC_DIR = cfg.VAULT / "22_Security"
_REPORTS = _SEC_DIR / "_Reports"
_BASELINE_FLAG = cfg.DATA / ".security_baseline_done"

_AUDIT_DIRECTIVE = (
    "Perform a full security audit of the FINESSE platform. First call `platform_audit` to get "
    "the real current state, and `vault_search` for any injected security requirements. Then "
    "produce your ranked findings report with an overall posture score 0-100 and concrete fixes.")


def _extract_score(text: str) -> int | None:
    m = re.search(r"(?:posture\s*score|score)\D{0,12}(\d{1,3})\s*/?\s*100", text, re.IGNORECASE)
    if not m:
        m = re.search(r"(\d{1,3})\s*/\s*100", text)
    if m:
        return max(0, min(100, int(m.group(1))))
    return None


def _evidence_summary(data: dict) -> str:
    """Compact, deterministic evidence block written verbatim into the report."""
    if not data:
        return "_platform_audit returned no data_\n"
    rbac = data.get("rbac", {})
    sec = data.get("secrets_in_code", {})
    hits = sec.get("hits", [])
    env = sec.get("env", {})
    audit = data.get("audit", {})
    cfgp = data.get("config_posture", {})
    wg = data.get("write_gating", {})
    hits_str = ", ".join(f"{h['file']}:{h['line']} ({h['type']})" for h in hits[:8]) if hits else "(none)"
    lines = [
        f"- **Roles:** {rbac.get('roles')} · admin/wildcard: {rbac.get('admin_wildcard_roles')} · lanes: {', '.join(rbac.get('lanes', []))}",
        f"- **Hardcoded-secret hits in source:** {len(hits)} → {hits_str}",
        f"- **.env gitignored:** {env.get('env_ignored')} · .gitignore present: {env.get('gitignore_present')} · .env present: {env.get('env_file_present')}",
        f"- **Write tools (human-gated):** {wg.get('write_tools')} · read tools: {len(wg.get('read_tools', []))}",
        f"- **Audit records:** {audit.get('records')} · outcomes: {audit.get('outcomes')} · anomalies: {audit.get('anomalies')}",
        f"- **Config issues:** {cfgp.get('config_issues') or 'none'}",
        f"- **Inventory:** {data.get('inventory')}",
    ]
    return "\n".join(lines) + "\n"


def _write_report(output: str, score: int | None, evidence: str, actor: str) -> str:
    _REPORTS.mkdir(parents=True, exist_ok=True)
    stamp = time.strftime("%Y%m%d-%H%M%S")
    fname = f"{stamp}_security_audit.md"
    body = (
        f"---\ntitle: Security Audit {stamp}\ntags: [security, audit, report]\n"
        f"posture_score: {score if score is not None else 'n/a'}\nby: {actor}\n---\n\n"
        f"# 🛡️ Security Audit — {stamp}\n\n"
        f"**Posture score:** {score if score is not None else 'n/a'}/100 · "
        f"generated by [[Security_Audit_Agent]]\n\n"
        f"## Evidence (platform_audit, deterministic)\n{evidence}\n"
        f"## Findings & fixes (agent analysis)\n\n{output}\n\n"
        f"> [[Security Posture]] · [[22_Security MOC]] · [[SASTRAVA OS MAP]]\n")
    (_REPORTS / fname).write_text(body, encoding="utf-8")

    # rolling latest-summary the CEO can pin
    rel = f"_Reports/{fname}"
    posture = (
        f"---\ntitle: Security Posture\ntags: [security, moc]\n---\n\n"
        f"# 🛡️ Security Posture (live)\n\n"
        f"**Latest score:** {score if score is not None else 'n/a'}/100 · updated {stamp}\n\n"
        f"Latest full report: [[{fname[:-3]}]]\n\n"
        f"## Evidence snapshot\n{evidence}\n"
        f"> The Security Audit Agent runs every {cfg.SECURITY_AUDIT_INTERVAL_MIN} min when "
        f"`SECURITY_AUDIT_ENABLED=1`. Feed it requirements via the data gateway (tag: security).\n")
    (_SEC_DIR / "Security Posture.md").write_text(posture, encoding="utf-8")
    return rel


async def run_audit(*, actor: str = "security_watch") -> dict:
    """Run one full audit: evidence -> agent -> report. Returns a summary dict."""
    from .agents.registry import registry

    # 1. deterministic evidence straight from the tool
    ev = await mcp.dispatch("platform_audit", {}, lane="security", actor=actor)
    data = ev.data if ev.ok else {}
    evidence = _evidence_summary(data)

    # 2. agentic analysis (grounds itself via the same tool + vault_search).
    #    Watchdog must be unbreakable: if NIM is slow/down we STILL write a report
    #    from the deterministic evidence rather than failing the whole audit.
    steps = 0
    try:
        agent = registry.spawn("security_audit", trace="secwatch")
        result = await agent.run(_AUDIT_DIRECTIVE)
        analysis, steps = result.output, result.steps
        score = _extract_score(analysis)
    except Exception as e:  # noqa: BLE001
        await bus.emit("error", "security", f"LLM analysis unavailable ({e}); wrote evidence-only report")
        analysis = (f"> ⚠️ LLM analysis unavailable this cycle ({type(e).__name__}). "
                    f"The deterministic evidence above is still valid; re-run when inference recovers.\n")
        score = None

    # 3. persist + alert (always)
    rel = await asyncio.to_thread(_write_report, analysis, score, evidence, actor)
    anomalies = (data.get("audit", {}) or {}).get("anomalies", [])
    low = score is not None and score < 70
    if low or anomalies:
        await bus.emit("error", "security", "⚠️ security posture needs attention"
                       + (f" (score {score}/100)" if score is not None else "")
                       + (f"; anomalies: {anomalies}" if anomalies else ""), trace="secwatch")
    else:
        await bus.emit("system", "security",
                       f"security audit clean (score {score if score is not None else 'n/a'}/100)")
    return {"score": score, "report": rel, "anomalies": anomalies,
            "evidence": data, "output": analysis, "steps": steps}


async def _baseline_harvest():
    """Harvest baseline security skills once, so the agent trains from the baseline."""
    if _BASELINE_FLAG.exists():
        return
    from .skills_harvester import harvest_repo
    total = 0
    for spec in cfg.SECURITY_HARVEST_REPOS:
        try:
            total += await harvest_repo(spec, actor="security_watch", max_files=25)
        except Exception as e:  # noqa: BLE001
            await bus.emit("error", "security", f"baseline harvest {spec}: {e}")
    try:
        _BASELINE_FLAG.write_text(f"{time.time()}", encoding="utf-8")
    except Exception:  # noqa: BLE001
        pass
    await bus.emit("learn", "security", f"baseline security skills harvested (+{total})")


async def security_loop():
    await bus.emit("system", "security",
                   f"security watch online (every {cfg.SECURITY_AUDIT_INTERVAL_MIN}m)")
    await _baseline_harvest()
    while True:
        try:
            await run_audit(actor="security_watch")
        except asyncio.CancelledError:
            raise
        except Exception as e:  # noqa: BLE001
            await bus.emit("error", "security", f"audit cycle error: {e}")
        await asyncio.sleep(max(300, cfg.SECURITY_AUDIT_INTERVAL_MIN * 60))
